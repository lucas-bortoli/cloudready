import type { DataFile, NodeIngredient, NodeMeal, NodeNutrient, NutrientUnits } from "./current";

const nutrientUnits: NutrientUnits = {
  energy: "kcal",
  totalCarbohydrate: "g",
  dietaryFiber: "g",
  totalSugars: "g",
  addedSugars: "g",
  protein: "g",
  totalFat: "g",
  saturatedFat: "g",
  transFat: "g",
  cholesterol: "mg",
  vitaminC: "mg",
  vitaminD: "mcg",
  sodium: "mg",
  calcium: "mg",
  iron: "mg",
  potassium: "mg",
};

type NutrientValues = Partial<Record<keyof NutrientUnits, number>>;

function nutrientNodes(values: NutrientValues): NodeNutrient[] {
  return Object.entries(values).map(([name, value]) => {
    const nutrient = name as keyof NutrientUnits;
    return {
      type: "nutrient",
      nutrient,
      value: value as number,
      unit: nutrientUnits[nutrient],
    } as NodeNutrient;
  });
}

function ingredient(
  name: string,
  amount: number,
  unit: NodeIngredient["unit"],
  nutrients: NutrientValues,
  children: NodeIngredient[] = [],
): NodeIngredient {
  return {
    type: "ingredient",
    name,
    amount,
    unit,
    referenceValue: 100,
    children: [...nutrientNodes(nutrients), ...children],
  };
}

function meal(name: string, children: NodeIngredient[]): NodeMeal {
  return { type: "meal", name, children };
}

